test("the fixture inventory mirrors the common list in tests/native.ts", () => {
  const native = readFileSync(join(root, "tests/native.ts"), "utf8");
  const start = native.indexOf("const fixtures: readonly Fixture[] = [\n");
  const listEnd = native.indexOf("\n];\n", start);
  assert.ok(start >= 0 && listEnd > start, "tests/native.ts fixture list");
  const expected = native
    .slice(native.indexOf("\n", start) + 1, listEnd)
    .split("\n")
    .map((line) => line.trim().replace(/,$/u, ""));
  const inventory = readFileSync(
    join(root, "tests/native/fixture-inventory.ts"),
    "utf8",
  );
  const groups = inventory.slice(
    inventory.indexOf("export const nativeFixtureGroups"),
  );
  const actual = [...groups.matchAll(/fixtures: (\[?)([\w.]+)\]?/gu)].map(
    (match) => (match[1] === "[" ? match[2] : `...${match[2]}`),
  );
  assert.deepEqual(actual, expected);
});
