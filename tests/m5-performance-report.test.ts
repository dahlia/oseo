test("runtime counters come from the last marker line", () => {
  const stderr =
    'OSEO_OBSERVATIONS {"allocations":1,"collections":0}\n' +
    "program output\n" +
    'OSEO_OBSERVATIONS {"allocations":7,"collections":2,"guardHits":3}\n';
  assert.deepEqual(parseRuntimeCounters(stderr), {
    allocations: 7,
    collections: 2,
  });
  assert.equal(parseRuntimeCounters("no marker\n"), undefined);
  assert.throws(
    () => parseRuntimeCounters('OSEO_OBSERVATIONS {"allocations":-1}\n'),
    /negative allocations/u,
  );
  assert.throws(
    () =>
      parseRuntimeCounters(
        'OSEO_OBSERVATIONS {"allocations":1,"collections":1.5}\n',
      ),
    /invalid collections/u,
  );
});

test("peak RSS parsers read GNU KiB and BSD bytes", () => {
  assert.equal(parseGnuTimeRss("12345\n"), 12_345);
  assert.equal(
    parseGnuTimeRss("Command exited with non-zero status 1\n99\n"),
    99,
  );
  assert.throws(() => parseGnuTimeRss(""), /no peak RSS/u);
  assert.equal(
    parseBsdTimeRss(
      "        0.01 real\n   2097152  maximum resident set size\n",
    ),
    2_048,
  );
  assert.equal(parseBsdTimeRss("1025  maximum resident set size\n"), 2);
  assert.throws(() => parseBsdTimeRss("0.01 real\n"), /maximum resident/u);
});

test("latency summaries use the middle sample", () => {
  assert.equal(median([5, 1, 3]), 3);
  assert.equal(median([4, 1, 3, 2]), 2.5);
  assert.throws(() => median([]), /empty sample/u);
  assert.deepEqual(summarizeLatency([9, 2, 4, 7, 3]), {
    max: 9,
    median: 4,
    min: 2,
  });
});

test("fixture files are measured, measured through, or excluded", () => {
  const classified = classifyFixtureFiles(
    ["z.ts", "a.ts", "a-cases.ts", "notes.txt", "lonely.ts"],
    new Set(["a.ts"]),
    new Map([
      ["a.ts", ["tests/native.ts"]],
      ["a-cases.ts", ["tests/a-cases.test.ts", "tests/native/fixtures/a.ts"]],
      ["z.ts", ["tests/z.test.ts"]],
      ["notes.txt", ["tests/z.test.ts"]],
    ]),
  );
  assert.deepEqual(classified, [
    {
      disposition: "measured-through",
      file: "a-cases.ts",
      owners: ["tests/native/fixtures/a.ts"],
    },
    { disposition: "measured", file: "a.ts", owners: [] },
    { disposition: "unreferenced", file: "lonely.ts", owners: [] },
    { disposition: "data", file: "notes.txt", owners: ["tests/z.test.ts"] },
    {
      disposition: "dedicated-harness",
      file: "z.ts",
      owners: ["tests/z.test.ts"],
    },
  ]);
});

test("aggregates sum per-fixture metrics and keep process maxima", () => {
  const aggregate = aggregateWorkloads(report.workloads);
  assert.deepEqual(aggregate, {
    allocations: 20,
    buildMs: 301.5,
    cBytes: 1_238_567,
    collections: 2,
    executableBytes: 70_000,
    frontendAndEmitMs: 30,
    latencyMedianMs: 9,
    maxRssKiB: 4_096,
    workloads: 3,
  });
  const missing = aggregateWorkloads([report.workloads[1]!]);
  assert.equal(missing.allocations, null);
  assert.equal(missing.maxRssKiB, null);
});

test("serialized measurements round-trip through the parser", () => {
  const text = serializeM5PerformanceMeasurements(report);
  assert.deepEqual(parseM5PerformanceMeasurements(text), report);
  const changed = text.replace('"cBytes"', '"sourceBytes"');
  assert.throws(
    () => parseM5PerformanceMeasurements(changed),
    /workload columns/u,
  );
});

test("the rendered section has aligned tables and a totals row", () => {
  const rendered = renderM5PerformanceReport(report);
  assert.match(rendered, /^\| Commit {2,}\| `0123abcd` +\|$/mu);
  assert.match(rendered, /\| Sanitizers +\| `address`, `undefined` +\|/u);
  const cRow = rendered
    .split("\n")
    .find((line) => line.startsWith("| Generated C bytes "));
  assert.equal(
    cRow
      ?.split("|")
      .map((cell) => cell.trim())
      .join("|"),
    "|Generated C bytes|1,238,567|2,000|2,000|1,234,567|",
  );
  assert.match(rendered, /^\| Peak RSS KiB +\| +n\/a \| +4,096 \|/mu);
  const totals = rendered
    .split("\n")
    .find((line) => line.startsWith("| Total "));
  assert.equal(
    totals
      ?.split("|")
      .map((cell) => cell.trim())
      .join("|"),
    "|Total|3|1,238,567|70,000|30.0|301.5|9.0|4,096|20|2|",
  );
  assert.match(rendered, /^\| \*a\.ts\* +\| +2 \|/mu);
  assert.match(rendered, /`broken` .*boom \\\| bang/u);
  assert.match(rendered, /\| \*a-cases\.ts\* +\| Measured through/u);
  assert.match(rendered, /\| \*c\.ts\* +\| Excluded: dedicated harness/u);
  assert.match(rendered, /2 of the 4 files/u);
  for (const line of rendered.split("\n")) {
    if (!line.startsWith("|")) assert.ok(line.length <= 80, line);
  }
  // Hongdown keeps a table whose cells are padded to one width per column.
  const tables = rendered
    .split("\n\n")
    .filter((block) => block.startsWith("|"));
  assert.equal(tables.length, 5);
  for (const block of tables) {
    const lengths = new Set(block.split("\n").map((line) => line.length));
    assert.equal(lengths.size, 1, block);
  }
});

test("section replacement needs exactly one marker pair", () => {
  const document = `Title\n\n${marker}\n\nold\n\n${end}\n\nAfter.\n`;
  assert.equal(
    replaceM5PerformanceSection(document, "new"),
    `Title\n\n${marker}\n\nnew\n\n${end}\n\nAfter.\n`,
  );
  assert.throws(
    () => replaceM5PerformanceSection("no markers", "new"),
    /exactly one generated section/u,
  );
  assert.throws(
    () => replaceM5PerformanceSection(`${document}${marker}\n`, "new"),
    /exactly one generated section/u,
  );
});

