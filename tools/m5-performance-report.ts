/** Runtime counters the tool keeps from the observation marker. */
export interface M5RuntimeCounters {
  readonly allocations: number;
  readonly collections: number;
}

/**
 * Read the last counter marker line from native stderr.
 *
 * The runtime prints this marker only for MIR compiled with
 * `observeSpecialization`; the protocol is the one *packages/testkit*
 * parses. A missing marker yields undefined rather than zero counts.
 */
export function parseRuntimeCounters(
  stderr: string,
): M5RuntimeCounters | undefined {
  const line = stderr
    .split("\n")
    .findLast((candidate) => candidate.startsWith(counterPrefix));
  if (line == null) return undefined;
  const parsed = parsedObject(
    JSON.parse(line.slice(counterPrefix.length)),
    "Runtime observation marker",
  );
  const counter = (key: string): number => {
    const value = parsed[key];
    if (!isNumber(value) || !Number.isSafeInteger(value)) {
      throw new Error(`Runtime observation has invalid ${key}.`);
    }
    if (value < 0) throw new Error(`Runtime observation has negative ${key}.`);
    return value;
  };
  return {
    allocations: counter("allocations"),
    collections: counter("collections"),
  };
}

/** Parse GNU time's `%M` output, the peak RSS in KiB on its last line. */
export function parseGnuTimeRss(text: string): number {
  const last = text.trim().split("\n").at(-1)?.trim() ?? "";
  if (!/^\d+$/u.test(last)) {
    throw new Error(`GNU time reported no peak RSS: ${JSON.stringify(text)}`);
  }
  return Number(last);
}

/** Parse BSD `time -l` stderr, which reports peak RSS in bytes. */
export function parseBsdTimeRss(stderr: string): number {
  const match = /(\d+)\s+maximum resident set size/u.exec(stderr);
  if (match?.[1] == null) {
    throw new Error("BSD time reported no maximum resident set size.");
  }
  return Math.ceil(Number(match[1]) / 1024);
}

/** Median of a non-empty sample; an even sample averages its middle pair. */
export function median(values: readonly number[]): number {
  if (values.length === 0) throw new Error("Median of an empty sample.");
  const sorted = values.toSorted((left, right) => left - right);
  const middle = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 1
    ? sorted[middle]!
    : (sorted[middle - 1]! + sorted[middle]!) / 2;
}

/** Summarize one latency sample in milliseconds. */
export function summarizeLatency(samples: readonly number[]): LatencySummary {
  return {
    max: Math.max(...samples),
    median: median(samples),
    min: Math.min(...samples),
  };
}

/** Round a millisecond measurement to the reported 0.1 ms resolution. */
export function roundMs(value: number): number {
  return Math.round(value * 10) / 10;
}

/**
 * Classify every file in *tests/native/fixtures/*.
 *
 * `importers` maps a fixture file name to the repository paths whose
 * source names it. A measured module's importers are not recorded, since
 * the common loop already owns it.
 */
export function classifyFixtureFiles(
  files: readonly string[],
  measuredModules: ReadonlySet<string>,
  importers: ReadonlyMap<string, readonly string[]>,
): readonly M5FixtureFile[] {
  return files.toSorted().map((file): M5FixtureFile => {
    if (measuredModules.has(file)) {
      return { disposition: "measured", file, owners: [] };
    }
    const owners = importers.get(file) ?? [];
    const through = owners.filter((path) =>
      measuredModules.has(path.slice(fixtureDirectory.length + 1)),
    );
    if (through.length > 0) {
      return { disposition: "measured-through", file, owners: through };
    }
    if (owners.length === 0) {
      return { disposition: "unreferenced", file, owners };
    }
    return {
      disposition: file.endsWith(".ts") ? "dedicated-harness" : "data",
      file,
      owners,
    };
  });
}

const dispositionLabels: ReadonlyMap<M5FixtureFile["disposition"], string> =
  new Map([
    ["data", "Excluded: data its owners read"],
    ["dedicated-harness", "Excluded: dedicated harness"],
    ["measured", "Measured"],
    ["measured-through", "Measured through its owner"],
    ["unreferenced", "Excluded: unreferenced"],
  ]);

function count(value: number): string {
  const [whole = "", fraction] = String(value).split(".");
  const grouped = whole.replace(/\B(?=(?:\d{3})+$)/gu, ",");
  return fraction == null ? grouped : `${grouped}.${fraction}`;
}

function decimal(value: number): string {
  const [whole, fraction] = value.toFixed(1).split(".");
  return `${count(Number(whole))}.${fraction}`;
}

function optional(
  value: number | null,
  format: (value: number) => string,
): string {
  return value == null ? "n/a" : format(value);
}

function table(header: readonly string[], rows: readonly string[][]): string {
  const all = [header, ...rows];
  const widths = header.map((_, column) =>
    Math.max(3, ...all.map((row) => (row[column] ?? "").length)),
  );
  const numeric = header.map((_, column) =>
    rows.every((row) =>
      /^(?:[0-9,]+(?:\.[0-9])?|n\/a)$/u.test(row[column] ?? ""),
    ),
  );
  const line = (row: readonly string[]): string =>
    "| " +
    row
      .map((cell, column) =>
        numeric[column] === true
          ? cell.padStart(widths[column] ?? 0)
          : cell.padEnd(widths[column] ?? 0),
      )
      .join(" | ") +
    " |";
  const rule =
    "| " +
    widths
      .map((width, column) =>
        numeric[column] === true
          ? "-".repeat(width - 1) + ":"
          : "-".repeat(width),
      )
      .join(" | ") +
    " |";
  return [line(header), rule, ...rows.map(line)].join("\n");
}

function sum(values: readonly number[]): number {
  return values.reduce((total, value) => total + value, 0);
}

function present(values: readonly (number | null)[]): readonly number[] {
  return values.filter((value): value is number => value != null);
}

/** Aggregates of one group of workloads, as the module table reports them. */
export interface M5WorkloadAggregate {
  readonly allocations: number | null;
  readonly buildMs: number;
  readonly cBytes: number;
  readonly collections: number | null;
  readonly executableBytes: number;
  readonly frontendAndEmitMs: number;
  readonly latencyMedianMs: number;
  readonly maxRssKiB: number | null;
  readonly workloads: number;
}

/**
 * Sum sizes, compile times, latency medians, and counters; keep the
 * largest executable and peak RSS, since summing processes is meaningless.
 */
export function aggregateWorkloads(
  workloads: readonly M5PerformanceWorkload[],
): M5WorkloadAggregate {
  const rss = present(workloads.map((workload) => workload.maxRssKiB));
  const allocations = present(workloads.map((item) => item.allocations));
  const collections = present(workloads.map((item) => item.collections));
  return {
    allocations: allocations.length === 0 ? null : sum(allocations),
    buildMs: roundMs(sum(workloads.map((item) => item.buildMs))),
    cBytes: sum(workloads.map((item) => item.cBytes)),
    collections: collections.length === 0 ? null : sum(collections),
    executableBytes: Math.max(
      0,
      ...workloads.map((item) => item.executableBytes),
    ),
    frontendAndEmitMs: roundMs(
      sum(workloads.map((item) => item.frontendMs + item.emitMs)),
    ),
    latencyMedianMs: roundMs(sum(workloads.map((item) => item.latency.median))),
    maxRssKiB: rss.length === 0 ? null : Math.max(...rss),
    workloads: workloads.length,
  };
}

function distribution(
  label: string,
  values: readonly number[],
  format: (value: number) => string,
  total: boolean,
): string[] {
  if (values.length === 0) return [label, "n/a", "n/a", "n/a", "n/a"];
  return [
    label,
    total ? format(sum(values)) : "n/a",
    format(median(values)),
    format(Math.min(...values)),
    format(Math.max(...values)),
  ];
}

function hostTable(report: M5PerformanceMeasurements): string {
  const { host, settings } = report;
  return table(
    ["Field", "Value"],
    [
      ["Commit", `\`${host.commit}\``],
      ["Clean tree", host.cleanTree ? "yes" : "no"],
      ["Measured at", report.measuredAt],
      ["Operating system", `\`${host.operatingSystem}\``],
      ["Architecture", host.architecture],
      ["CPU", host.cpuModel],
      ["Logical CPUs", String(host.logicalCpus)],
      ["Memory", `${decimal(host.memoryBytes / 1024 ** 3)} GiB`],
      ["Node.js", host.nodeVersion],
      ["Zig", host.zigVersion ?? "n/a"],
      ["Native target", `\`${settings.target}\``],
      [
        "Sanitizers",
        settings.sanitizers.length === 0
          ? "none"
          : settings.sanitizers.map((name) => `\`${name}\``).join(", "),
      ],
      ["Specialization policy", settings.specialization],
      ["Executions per workload", String(settings.runs)],
      ["Peak RSS command", settings.rssCommand ?? "n/a"],
      ["Runtime archive before warm-up", settings.runtimeArchiveBeforeWarmUp],
      ["Measurement wall time", `${decimal(report.measurementSeconds)} s`],
    ],
  );
}

/** Render the generated measurement section, without its markers. */
export function renderM5PerformanceReport(
  report: M5PerformanceMeasurements,
): string {
  const { workloads } = report;
  const summary = table(
    ["Metric", "Total", "Median", "Min", "Max"],
    [
      distribution(
        "Generated C bytes",
        workloads.map((item) => item.cBytes),
        count,
        true,
      ),
      distribution(
        "Executable bytes",
        workloads.map((item) => item.executableBytes),
        count,
        true,
      ),
      distribution(
        "Frontend, MIR, and C emission ms",
        workloads.map((item) => roundMs(item.frontendMs + item.emitMs)),
        decimal,
        true,
      ),
      distribution(
        "C compile and link ms",
        workloads.map((item) => item.buildMs),
        decimal,
        true,
      ),
      distribution(
        "Median execution latency ms",
        workloads.map((item) => item.latency.median),
        decimal,
        true,
      ),
      distribution(
        "Peak RSS KiB",
        present(workloads.map((item) => item.maxRssKiB)),
        count,
        false,
      ),
      distribution(
        "Runtime allocations",
        present(workloads.map((item) => item.allocations)),
        count,
        true,
      ),
      distribution(
        "Runtime collections",
        present(workloads.map((item) => item.collections)),
        count,
        true,
      ),
    ],
  );
  const modules = [...new Set(workloads.map((item) => item.module))].toSorted();
  const moduleRow = (label: string, aggregate: M5WorkloadAggregate) => [
    label,
    count(aggregate.workloads),
    count(aggregate.cBytes),
    count(aggregate.executableBytes),
    decimal(aggregate.frontendAndEmitMs),
    decimal(aggregate.buildMs),
    decimal(aggregate.latencyMedianMs),
    optional(aggregate.maxRssKiB, count),
    optional(aggregate.allocations, count),
    optional(aggregate.collections, count),
  ];
  const perModule = table(
    [
      "Module",
      "Fixtures",
      "C bytes",
      "Largest executable bytes",
      "Frontend ms",
      "C build ms",
      "Latency ms",
      "Largest peak RSS KiB",
      "Allocations",
      "Collections",
    ],
    [
      ...modules.map((module) =>
        moduleRow(
          `*${module}*`,
          aggregateWorkloads(
            workloads.filter((item) => item.module === module),
          ),
        ),
      ),
      moduleRow("Total", aggregateWorkloads(workloads)),
    ],
  );
  const failures =
    report.failures.length === 0
      ? ["No fixture in the common loop failed to build or execute."]
      : [
          "These fixtures in the common loop failed and are excluded from" +
            " every table:",
          "",
          table(
            ["Fixture", "Module", "Phase", "Message"],
            report.failures.map((failure) => [
              `\`${failure.name}\``,
              `*${failure.module}*`,
              failure.phase,
              failure.message.replaceAll("|", "\\|"),
            ]),
          ),
        ];
  const notMeasured = report.fixtureFiles.filter(
    (file) => file.disposition !== "measured",
  );
  const files = table(
    ["File", "Disposition", "Owners"],
    notMeasured.map((file) => [
      `*${file.file}*`,
      dispositionLabels.get(file.disposition) ?? file.disposition,
      file.owners.length === 0
        ? "none"
        : file.owners
            .map((path) =>
              path.startsWith(`${fixtureDirectory}/`)
                ? `*${path.slice(fixtureDirectory.length + 1)}*`
                : `*${path}*`,
            )
            .join(", "),
    ]),
  );
  const measuredFiles = report.fixtureFiles.length - notMeasured.length;
  return [
    hostTable(report),
    "",
    `${count(workloads.length)} fixtures from ${count(modules.length)}` +
      " modules were measured.",
    "Totals sum over fixtures. The RSS row has no total because peak RSS",
    "does not add across processes.",
    "",
    summary,
    "",
    "Each module row sums its fixtures, except the executable and peak RSS",
    "columns, which report the largest fixture. Latency sums per-fixture",
    "medians. Frontend time includes C emission.",
    "",
    perModule,
    "",
    ...failures,
    "",
    `${count(measuredFiles)} of the ${count(report.fixtureFiles.length)}` +
      " files under *tests/native/fixtures/* are common-loop modules. The",
    "others are imported by one and measured through it, or excluded:",
    "a dedicated test owns them with a harness this tool does not",
    "reproduce, or they are not modules.",
    "",
    files,
  ].join("\n");
}

/** Replace the generated section of the performance report. */
export function replaceM5PerformanceSection(
  document: string,
  rendered: string,
): string {
  const start = document.indexOf(sectionStart);
  const end = document.indexOf(sectionEnd);
  if (
    start < 0 ||
    end < start ||
    document.indexOf(sectionStart, start + 1) >= 0 ||
    document.indexOf(sectionEnd, end + 1) >= 0
  ) {
    throw new Error(
      `${m5PerformanceReportPath} needs exactly one generated section.`,
    );
  }
  return (
    document.slice(0, start + sectionStart.length) +
    `\n\n${rendered}\n\n` +
    document.slice(end)
  );
}

const workloadColumns = [
  "name",
  "module",
  "cBytes",
  "executableBytes",
  "frontendMs",
  "emitMs",
  "buildMs",
  "runtimeArchive",
  "latencyMedianMs",
  "latencyMinMs",
  "latencyMaxMs",
  "maxRssKiB",
  "allocations",
  "collections",
] as const;

type WorkloadCell = number | string | null;

/**
 * Serialize measurements with one row array per workload.
 *
 * Column-oriented rows keep the checked-in JSON a fraction of the size of
 * one object per workload.
 */
export function serializeM5PerformanceMeasurements(
  report: M5PerformanceMeasurements,
): string {
  const rows = report.workloads.map((item): readonly WorkloadCell[] => [
    item.name,
    item.module,
    item.cBytes,
    item.executableBytes,
    item.frontendMs,
    item.emitMs,
    item.buildMs,
    item.runtimeArchive,
    item.latency.median,
    item.latency.min,
    item.latency.max,
    item.maxRssKiB,
    item.allocations,
    item.collections,
  ]);
  const { workloads: _, ...rest } = report;
  return `${JSON.stringify(
    { ...rest, workloadColumns, workloads: rows },
    null,
    2,
  )}\n`;
}

function field(row: readonly WorkloadCell[], name: string): WorkloadCell {
  const index = workloadColumns.findIndex((column) => column === name);
  if (index < 0 || index >= row.length) {
    throw new Error(`Workload row lacks ${name}.`);
  }
  return row[index] ?? null;
}

function numberField(row: readonly WorkloadCell[], name: string): number {
  const value = field(row, name);
  if (!isNumber(value)) throw new Error(`${name} is not a number.`);
  return value;
}

function nullableNumber(
  row: readonly WorkloadCell[],
  name: string,
): number | null {
  const value = field(row, name);
  return value == null ? null : numberField(row, name);
}

function stringField(row: readonly WorkloadCell[], name: string): string {
  const value = field(row, name);
  if (!isString(value)) throw new Error(`${name} is not a string.`);
  return value;
}

/** Parse the checked-in JSON written by the serializer. */
export function parseM5PerformanceMeasurements(
  text: string,
): M5PerformanceMeasurements {
  // SAFETY: The serializer owns this format; workload rows are checked
  // field by field below, and the report check renders every other field.
  const parsed = JSON.parse(text) as Omit<
    M5PerformanceMeasurements,
    "workloads"
  > & {
    readonly workloadColumns: readonly string[];
    readonly workloads: readonly (readonly WorkloadCell[])[];
  };
  if (parsed.schema !== 1) throw new Error("Unknown measurement schema.");
  if (
    JSON.stringify(parsed.workloadColumns) !== JSON.stringify(workloadColumns)
  )
    throw new Error("Unexpected workload columns.");
  const { workloadColumns: _, workloads, ...rest } = parsed;
  return {
    ...rest,
    workloads: workloads.map((row): M5PerformanceWorkload => {
      const archive = stringField(row, "runtimeArchive");
      if (archive !== "built" && archive !== "cached") {
        throw new Error(`Unknown runtime archive state ${archive}.`);
      }
      return {
        allocations: nullableNumber(row, "allocations"),
        buildMs: numberField(row, "buildMs"),
        cBytes: numberField(row, "cBytes"),
        collections: nullableNumber(row, "collections"),
        emitMs: numberField(row, "emitMs"),
        executableBytes: numberField(row, "executableBytes"),
        frontendMs: numberField(row, "frontendMs"),
        latency: {
          max: numberField(row, "latencyMaxMs"),
          median: numberField(row, "latencyMedianMs"),
          min: numberField(row, "latencyMinMs"),
        },
        maxRssKiB: nullableNumber(row, "maxRssKiB"),
        module: stringField(row, "module"),
        name: stringField(row, "name"),
        runtimeArchive: archive,
      };
    }),
  };
}

function firstLine<Candidate>(error: Candidate): string {
  const text = error instanceof Error ? error.message : String(error);
  let cause = error instanceof Error ? error.cause : undefined;
  let detail = "";
  while (cause instanceof Error) {
    detail = cause.message;
    cause = cause.cause;
  }
  return (detail === "" ? text : detail).split("\n")[0]!.slice(0, 160);
}

function command(file: string, args: readonly string[]): string | null {
  const result = spawnSync(file, args, { encoding: "utf8", timeout: 30_000 });
  return result.status === 0 ? result.stdout.trim() : null;
}

function describeHost(toolchain: NativeToolchain): M5PerformanceHost {
  const git = (args: readonly string[]): string =>
    execFileSync("git", ["--no-optional-locks", ...args], {
      cwd: repositoryRoot,
      encoding: "utf8",
    }).trim();
  return {
    architecture: arch(),
    cleanTree: git(["status", "--porcelain"]) === "",
    commit: git(["rev-parse", "HEAD"]),
    cpuModel: cpus()[0]?.model.trim() ?? "unknown",
    logicalCpus: cpus().length,
    memoryBytes: totalmem(),
    nodeVersion: process.version,
    operatingSystem: `${type()} ${release()}`,
    toolchainIdentity: toolchain.identity ?? null,
    zigVersion: command("zig", ["version"]),
  };
}

function rssCommand(): string | null {
  if (!existsSync("/usr/bin/time")) return null;
  if (platform() === "linux") return "/usr/bin/time -f %M";
  if (platform() === "darwin") return "/usr/bin/time -l";
  return null;
}

function importersOf(files: readonly string[]): Map<string, string[]> {
  const sources: string[] = [];
  const walk = (directory: string): void => {
    for (const entry of readdirSync(join(repositoryRoot, directory), {
      withFileTypes: true,
    })) {
      const path = `${directory}/${entry.name}`;
      if (entry.isDirectory()) walk(path);
      else if (entry.isFile() && path.endsWith(".ts")) sources.push(path);
    }
  };
  walk("tests");
  const importers = new Map<string, string[]>();
  for (const path of sources.toSorted()) {
    const text = readFileSync(join(repositoryRoot, path), "utf8");
    for (const file of files) {
      const stem = file.replace(/\.ts$/u, "");
      const local = path.startsWith(`${fixtureDirectory}/`)
        ? [`"./${file}"`, `"./${stem}"`]
        : [];
      const needles = [
        `fixtures/${file}"`,
        `fixtures/${stem}"`,
        `fixtures/${file}\``,
        ...local,
      ];
      if (
        `${fixtureDirectory}/${file}` !== path &&
        needles.some((needle) => text.includes(needle))
      ) {
        importers.set(file, [...(importers.get(file) ?? []), path]);
      }
    }
  }
  return importers;
}

/** Observations from the latency and RSS executions of one build. */
interface ExecutionSample {
  readonly counters: M5RuntimeCounters | undefined;
  readonly latency: LatencySummary;
  readonly maxRssKiB: number | null;
}

interface MeasurementOptions {
  readonly only?: ReadonlySet<string>;
  readonly runs: number;
  readonly specialization: SpecializationMode;
}

/** Build, execute, and measure every common-loop fixture in order. */
async function measure(
  options: MeasurementOptions,
): Promise<M5PerformanceMeasurements> {
  const started = performance.now();
  const [
    { cBackend },
    { defaultComponents },
    compiler,
    { createNodeHost },
    { cRuntimeProvider },
    { withNativeFixture },
    { nativeToolchain },
    { nativeFixtureGroups },
  ] = await Promise.all([
    import("../packages/backend-c/src/index.ts"),
    import("../packages/cli/src/index.ts"),
    import("../packages/compiler/src/index.ts"),
    import("../packages/host/src/index.ts"),
    import("../packages/runtime-c/src/index.ts"),
    import("../packages/testkit/src/index.ts"),
    import("../tests/native-toolchain.ts"),
    import("../tests/native/fixture-inventory.ts"),
  ]);
  // Fixtures observe the default collector schedule, not the forced one
  // that tests/native.ts selects for some of them, and a pinned zone.
  delete process.env.OSEO_GC_EVERY_SAFEPOINT;
  process.env.TZ = "UTC";
  const baseHost = createNodeHost();
  const executionHost = baseHost.executionHost;
  if (executionHost == null) throw new Error("Unknown execution host.");
  const target: TargetDescription | undefined =
    compiler.targetForExecutionHost(executionHost);
  if (target == null || !compiler.canExecuteTarget(executionHost, target)) {
    throw new Error(
      `No executable native target for ${executionHost.operatingSystem}/` +
        `${executionHost.architecture}.`,
    );
  }
  const { specialization } = options;
  const rss = rssCommand();
  const scratch = mkdtempSync(join(tmpdir(), "oseo-m5-performance-"));

  /** Timings and artifacts that the wrapped components accumulate. */
  interface BuildRecord {
    buildMs: number;
    cBytes: number;
    emitMs: number;
    directory?: string;
    plan?: NativeBuildPlan;
    runtimeArchive: "built" | "cached";
  }

  const build = async (
    name: string,
    source: string,
    test262Host: boolean,
  ): Promise<{ readonly frontendMs: number; readonly record: BuildRecord }> => {
    const frontendStart = performance.now();
    const compilation = compiler.compileSource(
      defaultComponents.frontend,
      { source, sourceId: `${name}.ts` },
      { observeSpecialization: true, specialization, test262Host },
    );
    const frontendMs = performance.now() - frontendStart;
    if (compilation.mir == null || compilation.diagnostics.length > 0) {
      throw Object.assign(
        new Error(
          compilation.diagnostics[0]?.message ?? "compilation produced no MIR",
        ),
        { phase: "compile" },
      );
    }
    const record: BuildRecord = {
      buildMs: 0,
      cBytes: 0,
      emitMs: 0,
      runtimeArchive: "built",
    };
    const backend: NativeBackend = {
      ...cBackend,
      emit(input) {
        const emitStart = performance.now();
        const emitted = cBackend.emit(input);
        record.emitMs += performance.now() - emitStart;
        // Split units are short wrappers that each include the full source,
        // so the emitted source counts once beside every wrapper.
        for (const unit of [emitted, ...(emitted.compilationUnits ?? [])]) {
          record.cBytes += Buffer.byteLength(unit.source, "utf8");
        }
        return emitted;
      },
    };
    const toolchain: NativeToolchain = {
      ...nativeToolchain,
      createBuildPlan(input) {
        record.runtimeArchive =
          input.prebuiltRuntimeArchivePath == null ? "built" : "cached";
        record.plan = nativeToolchain.createBuildPlan(input);
        return record.plan;
      },
    };
    const host: CompilerHost = {
      ...baseHost,
      async makeTemporaryDirectory(prefix) {
        record.directory = await baseHost.makeTemporaryDirectory(prefix);
        return record.directory;
      },
      async run(request) {
        const runStart = performance.now();
        const result = await baseHost.run(request);
        if (record.plan?.requests.includes(request) === true) {
          record.buildMs += performance.now() - runStart;
        }
        return result;
      },
    };
    try {
      await withNativeFixture(
        {
          agents: compilation.agents ?? [],
          backend,
          host,
          input: compilation.mir,
          keepArtifacts: true,
          operation: "compile",
          runtime: cRuntimeProvider,
          target,
          toolchain,
        },
        () => undefined,
      );
    } catch (error) {
      throw Object.assign(new Error(firstLine(error)), { phase: "build" });
    }
    return { frontendMs, record };
  };

  const execute = (record: BuildRecord): ExecutionSample => {
    const executable = record.plan?.executablePath;
    if (executable == null || record.directory == null) {
      throw new Error("The build left no executable.");
    }
    const samples: number[] = [];
    let counters: M5RuntimeCounters | undefined;
    for (let run = 0; run < options.runs; run++) {
      const runStart = performance.now();
      const result = spawnSync(executable, [], {
        cwd: record.directory,
        encoding: "utf8",
        maxBuffer: outputLimit,
        timeout: executionTimeout,
      });
      samples.push(performance.now() - runStart);
      if (result.error != null || result.status !== 0) {
        throw Object.assign(
          new Error(
            `exit ${result.status ?? result.signal}: ` +
              firstLine(result.error ?? result.stderr),
          ),
          { phase: "execute" },
        );
      }
      if (run === 0) counters = parseRuntimeCounters(result.stderr);
    }
    let maxRssKiB: number | null = null;
    if (rss === "/usr/bin/time -f %M") {
      const output = join(scratch, "rss.txt");
      const result = spawnSync(
        "/usr/bin/time",
        ["-f", "%M", "-o", output, executable],
        {
          cwd: record.directory,
          encoding: "utf8",
          maxBuffer: outputLimit,
          timeout: executionTimeout,
        },
      );
      if (result.status !== 0) throw new Error("The RSS run failed.");
      maxRssKiB = parseGnuTimeRss(readFileSync(output, "utf8"));
    } else if (rss === "/usr/bin/time -l") {
      const result = spawnSync("/usr/bin/time", ["-l", executable], {
        cwd: record.directory,
        encoding: "utf8",
        maxBuffer: outputLimit,
        timeout: executionTimeout,
      });
      if (result.status !== 0) throw new Error("The RSS run failed.");
      maxRssKiB = parseBsdTimeRss(result.stderr);
    }
    return { counters, latency: summarizeLatency(samples), maxRssKiB };
  };

  const workloads: M5PerformanceWorkload[] = [];
  const failures: M5PerformanceFailure[] = [];
  let runtimeArchiveBeforeWarmUp: "built" | "cached";
  try {
    // The warm-up publishes the runtime archive, so every measured build
    // links the cached archive instead of the first one compiling it.
    const warmUp = await build("warm-up", 'console.log("warm");', false);
    runtimeArchiveBeforeWarmUp = warmUp.record.runtimeArchive;
    if (warmUp.record.directory != null) {
      await baseHost.remove(warmUp.record.directory);
    }
    const groups: readonly NativeFixtureGroup[] = nativeFixtureGroups;
    const selected = groups.flatMap((group) =>
      group.fixtures
        .filter((fixture) => options.only?.has(fixture.name) ?? true)
        .map((fixture) => ({ fixture, module: group.module })),
    );
    for (const [index, { fixture, module }] of selected.entries()) {
      process.stderr.write(
        `[${index + 1}/${selected.length}] ${fixture.name}\n`,
      );
      let record: BuildRecord | undefined;
      try {
        const built = await build(
          fixture.name,
          fixture.source,
          fixture.test262Host === true,
        );
        record = built.record;
        const executed = execute(record);
        workloads.push({
          allocations: executed.counters?.allocations ?? null,
          buildMs: roundMs(record.buildMs),
          cBytes: record.cBytes,
          collections: executed.counters?.collections ?? null,
          emitMs: roundMs(record.emitMs),
          executableBytes: statSync(record.plan!.executablePath).size,
          frontendMs: roundMs(built.frontendMs),
          latency: {
            max: roundMs(executed.latency.max),
            median: roundMs(executed.latency.median),
            min: roundMs(executed.latency.min),
          },
          maxRssKiB: executed.maxRssKiB,
          module,
          name: fixture.name,
          runtimeArchive: record.runtimeArchive,
        });
      } catch (error) {
        const phase =
          error instanceof Error && "phase" in error ? error.phase : "execute";
        failures.push({
          message: firstLine(error),
          module,
          name: fixture.name,
          phase: phase === "compile" || phase === "build" ? phase : "execute",
        });
        process.stderr.write(`  failed: ${firstLine(error)}\n`);
      } finally {
        if (record?.directory != null) {
          await baseHost.remove(record.directory);
        }
      }
    }
  } finally {
    rmSync(scratch, { force: true, recursive: true });
  }
  const files = readdirSync(join(repositoryRoot, fixtureDirectory));
  const measuredModules = new Set(
    nativeFixtureGroups.map((group) => group.module),
  );
  return {
    failures,
    fixtureFiles: classifyFixtureFiles(
      files,
      measuredModules,
      importersOf(files),
    ),
    host: describeHost(nativeToolchain),
    measuredAt: new Date().toISOString().slice(0, 10),
    measurementSeconds: Math.round((performance.now() - started) / 100) / 10,
    schema: 1,
    settings: {
      rssCommand: rss,
      runs: options.runs,
      runtimeArchiveBeforeWarmUp,
      sanitizers: target.sanitizers,
      specialization,
      target: target.name,
    },
    workloads,
  };
}

function read(path: string): string {
  return readFileSync(join(repositoryRoot, path), "utf8");
}

/** Render the checked-in JSON into the checked-in report's section. */
export function renderCheckedInReport(document: string, json: string): string {
  return replaceM5PerformanceSection(
    document,
    renderM5PerformanceReport(parseM5PerformanceMeasurements(json)),
  );
}

const entry = process.argv[1];
if (entry != null && resolve(entry) === fileURLToPath(import.meta.url)) {
  const usage =
    "usage: node tools/m5-performance-report.ts (--print [--json PATH] |" +
    " --update) [--runs N] [--specialization enabled|disabled]" +
    " [--only NAME]...";
  const { values } = parseArgs({
    options: {
      json: { type: "string" },
      only: { multiple: true, type: "string" },
      print: { type: "boolean" },
      runs: { type: "string" },
      specialization: { type: "string" },
      update: { type: "boolean" },
    },
  });
  const runs = Number(values.runs ?? "5");
  if (
    values.print === values.update ||
    !Number.isSafeInteger(runs) ||
    runs < 1 ||
    (values.update === true && values.json != null)
  ) {
    throw new Error(usage);
  }
  const specialization = values.specialization ?? "enabled";
  if (specialization !== "enabled" && specialization !== "disabled") {
    throw new Error(usage);
  }
  if (
    values.update === true &&
    (values.only != null || specialization !== "enabled")
  ) {
    throw new Error(
      "--update records every fixture under the default policy; drop" +
        " --only and --specialization.",
    );
  }
  const measurementOptions: MeasurementOptions =
    values.only == null
      ? { runs, specialization }
      : { only: new Set(values.only), runs, specialization };
  const report = await measure(measurementOptions);
  const json = serializeM5PerformanceMeasurements(report);
  if (values.update === true) {
    writeFileSync(join(repositoryRoot, m5PerformanceMeasurementsPath), json);
    writeFileSync(
      join(repositoryRoot, m5PerformanceReportPath),
      renderCheckedInReport(read(m5PerformanceReportPath), json),
    );
    console.log(`m5-performance-report updated ${m5PerformanceReportPath}`);
  } else {
    if (values.json != null) writeFileSync(values.json, json);
    console.log(renderM5PerformanceReport(report));
  }
}
